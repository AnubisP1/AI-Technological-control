-- ============================================================
-- 08. Типовые технические требования по ОСТ 1 02504-84
--
-- Источник: ОСТ 1 02504-84 "Типовые формулировки изложения технических
-- требований на чертежах" (см. ../../../../../../БД НСИ/ТТ и оформление/
-- типовые формлировки ТТ.pdf) — реальный отраслевой авиационный
-- стандарт (не выдуманная нормативка). Объём ограничен по решению
-- пользователя (2026-08-02): только таблицы, относящиеся к деталям из
-- проката с механической обработкой (табл. 11 "Типовые формулировки ТТ
-- на чертежах деталей, подлежащих механической обработке", табл. 16
-- "...деталей, подлежащих поверхностному упрочнению") — соответствует
-- реальным тестовым fixture проекта (вал из проката, не отливка/
-- штамповка). Остальные 23 таблицы стандарта (отливки, штамповки,
-- сварка, клёпка, пружины и т.д.) НЕ перенесены — не относятся к
-- текущим тестовым данным, могут быть добавлены отдельной задачей.
--
-- Стандарт даёт типовые ФОРМУЛИРОВКИ с полями для заполнения
-- конструктором ('_____'), а не готовые числа — где в источнике стоит
-- прочерк, соответствующее поле здесь оставлено NULL, а не выдумано.
-- ============================================================

-- Типовые пункты технических требований по механической обработке
-- (табл. 11 ОСТ 1 02504-84) — привязаны к operation_type, чтобы при
-- автоподборе операции можно было подсказать типовую формулировку ТТ,
-- относящуюся к этой операции.
CREATE TABLE machining_requirement_template (
    id                      INTEGER PRIMARY KEY AUTOINCREMENT,
    operation_type_id        INTEGER REFERENCES operation_type(id),  -- NULL — требование общее, не привязано к конкретному виду операции
    code                       VARCHAR(40) NOT NULL UNIQUE,   -- 'CARBURIZE_HRC', 'CNC_MACHINING', 'THREAD_ROLLING', 'MILL_UNDERCUT', 'UNSPEC_TOLERANCE', 'THREAD_SPEC', 'THREAD_RUNOUT'
    formulation_template        TEXT NOT NULL,   -- типовая формулировка дословно из ОСТ, с полями-прочерками как есть
    reference_standard            VARCHAR(60),     -- 'ОСТ 1 00022-80' и т.п. — куда смотреть за конкретными числами, если стандарт сам их не даёт
    notes                           TEXT             -- "Справочные данные и документы" из таблицы источника
);

-- Методы поверхностного упрочнения (табл. 16 ОСТ 1 02504-84) — по
-- материалу заготовки, т.к. источник группирует методы именно так
-- (для сталей — виброшлифование, для титановых сплавов —
-- пневмодинамический наклёп и т.д.).
CREATE TABLE surface_hardening_method (
    id                  INTEGER PRIMARY KEY AUTOINCREMENT,
    material_group_id     INTEGER REFERENCES material_group(id),  -- NULL — метод общий (не привязан к конкретной группе материала)
    method_name             VARCHAR(200) NOT NULL,   -- 'Виброшлифование', 'Пневмодинамический наклёп', 'Обкатка', 'Раскатывание отверстий', 'Виброгалтовка', 'Алмазное выглаживание', 'Пескоструйная обработка корундовым песком', 'Дробеструйный метод', 'Ударно-барабанный способ'
    reference_instruction     VARCHAR(100) NOT NULL,   -- 'Инструкция ВИАМ № 901-72', 'Инструкция ВИАМ № 1039-74', 'ПИ 1.4.379-77' и т.п. — дословно из источника
    applicable_to               TEXT                     -- 'для сталей', 'для титановых сплавов', 'для алюминиевых сплавов' — дословно из "Справочные данные" источника
);
