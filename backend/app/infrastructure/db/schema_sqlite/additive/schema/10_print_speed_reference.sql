-- 10. Типовая объёмная производительность печати по технологии
-- (Фаза 17, по решению пользователя 2026-08-03: точный расчёт времени
-- печати/расхода материала, не оставлять графы карты пустыми).
--
-- Значения — типовые инженерные ориентиры для настроек по умолчанию
-- (не измеренные лабораторные данные конкретного принтера/материала —
-- в проекте нет собственных замеров, а paспортные данные принтеров
-- НСИ не включают линейную скорость печати/объёмную производительность,
-- см. printer_model в 02_printers.sql). Указан источник каждой строки.
-- Оценка через объёмную производительность — стандартный инженерный
-- подход при отсутствии слайсер-специфичных данных.
-- ============================================================

CREATE TABLE print_speed_reference (
    id                          INTEGER PRIMARY KEY AUTOINCREMENT,
    am_technology_id              INTEGER NOT NULL UNIQUE REFERENCES am_technology(id),
    volumetric_rate_mm3_s            NUMERIC(8,2) NOT NULL,  -- типовая объёмная производительность печати, мм³/с
    source                              TEXT NOT NULL
);
